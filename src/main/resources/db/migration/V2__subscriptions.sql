CREATE TABLE brief_subscriber (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT NOT NULL UNIQUE,
 status TEXT NOT NULL,
 news_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 technology_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 generation BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE brief_project_selection (
 subscriber_id BIGINT NOT NULL REFERENCES brief_subscriber(id),
 project TEXT NOT NULL,
 selected_at TIMESTAMPTZ NOT NULL,
 PRIMARY KEY (subscriber_id, project)
);
CREATE TABLE brief_subscription_token (
 digest TEXT PRIMARY KEY,
 subscriber_id BIGINT NOT NULL REFERENCES brief_subscriber(id),
 purpose TEXT NOT NULL,
 generation BIGINT NOT NULL,
 expires_at TIMESTAMPTZ NOT NULL,
 consumed_at TIMESTAMPTZ
);
CREATE TABLE brief_request_limit (
 kind TEXT NOT NULL,
 value TEXT NOT NULL,
 window_start TIMESTAMPTZ NOT NULL,
 count INTEGER NOT NULL,
 PRIMARY KEY (kind, value)
);
